import { StoredProcedureDoc } from '../types/proc';

export function generateMarkdownTechnicalReport(proc: StoredProcedureDoc): string {
  const md = `# TECHNICAL SPECIFICATION: ${proc.name}
**Schema:** \`${proc.schema}\` | **Dialect:** \`${proc.dialect}\` | **Auth Mode:** \`${proc.authIdType}\`
**Author:** ${proc.author} | **Last Modified:** ${proc.lastModifiedDate}
**IWS Schedule:** \`${proc.iwsJobSchedule || 'Manual / Triggered'}\`

---

## 1. Executive Summary & Business Purpose
${proc.purpose}

---

## 2. Technical Parameter Specification
| Parameter Name | Mode | Data Type | Default Value | Nullable | Business Description |
| :--- | :--- | :--- | :--- | :--- | :--- |
${proc.parameters.map(p => `| \`${p.name}\` | **${p.mode}** | \`${p.dataType}\` | \`${p.defaultValue || 'None'}\` | ${p.isNullable ? 'Yes' : 'No'} | ${p.businessDescription} |`).join('\n')}

---

## 3. CRUD & Data Lineage Matrix
| Target Table | Schema | Operations | Columns Accessed |
| :--- | :--- | :--- | :--- |
${proc.crudMatrix.map(c => `| \`${c.tableName}\` | \`${c.schema || proc.schema}\` | \`${c.operations.join(', ')}\` | \`${c.columnsAccessed.join(', ')}\` |`).join('\n')}

---

## 4. Dependencies & Invocation Call Tree
${proc.dependencies.length > 0 ? proc.dependencies.map(d => `- **${d.type}**: \`${d.name}\` (${d.direction}) - ${d.description || 'Core system routine'}`).join('\n') : '*No external packaged routines or database links declared.*'}

---

## 5. Architectural Quality, Complexity & Risk Findings
- **Lines of Code:** ${proc.metrics.linesOfCode} (Comments: ${proc.metrics.commentLines})
- **Cyclomatic Complexity:** ${proc.metrics.cyclomaticComplexity} (Nesting Depth: ${proc.metrics.nestingDepth})
- **Maintainability Index:** ${proc.metrics.maintainabilityIndex} / 100
- **Risk Score:** ${proc.metrics.riskScore} / 100

${proc.riskFindings.length > 0 ? proc.riskFindings.map(r => `### [${r.severity}] ${r.title}
- **Category:** ${r.category}
- **Detail:** ${r.detail}
- **Action Required:** ${r.recommendation}
`).join('\n') : '✅ *No high-severity architectural hazards detected.*'}

---

## 6. Java 21 / Spring Boot 3.4.0 Fluent DSL Invocation
\`\`\`java
${proc.sampleExecutionSnippet.javaFluentDsl}
\`\`\`

---
*Report automatically generated by Florida Lottery Enterprise Stored Procedure Documenter.*
`;
  return md;
}

