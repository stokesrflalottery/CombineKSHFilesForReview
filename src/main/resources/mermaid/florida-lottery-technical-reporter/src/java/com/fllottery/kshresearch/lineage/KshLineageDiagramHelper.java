            g2d.setFont(new Font("SansSerif", Font.BOLD, 12));
            g2d.drawString(truncate(shortenPath(envName), 26), col3X + 16, envY + 48);
            g2d.setFont(new Font("SansSerif", Font.PLAIN, 11));
            g2d.setColor(new Color(0x64, 0x74, 0x8B));
            g2d.drawString("Database TNS & System Paths", col3X + 16, envY + 70);

            // Arrow: Env -> KSH (incoming)
            drawConnector(g2d, col3X, envY + 45, col2X + cardW, kshY + 120, "Sources", new Color(0x0D, 0x94, 0x88));

            // Tier 4: Downstream Assets (Tables, Logs, Reports)
            int tableY = 80;
            List<ScriptReferenceDoc> tables = script.getReferencesByType(ScriptReferenceType.DATABASE_TABLE);
            String tblName = !tables.isEmpty() ? tables.get(0).getTarget() : "ARTABAL";
            drawCard(g2d, col4X, tableY, cardW, 100, "TIER 4A: RELATIONAL TABLE", AWT_FOREST_GREEN);
            g2d.setColor(new Color(0x1E, 0x29, 0x3B));
