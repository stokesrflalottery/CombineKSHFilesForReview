            g2d.drawString("Table: " + tblName, col4X + 16, tableY + 48);
            g2d.setFont(new Font("SansSerif", Font.PLAIN, 12));
            g2d.setColor(new Color(0x64, 0x74, 0x8B));
            g2d.drawString("Operation: DML Updates / Inserts", col4X + 16, tableY + 74);

            // Arrow: Proc -> Table
            drawConnector(g2d, col3X + cardW, procY + 60, col4X, tableY + 50, "Modifies", AWT_FOREST_GREEN);

            // Tier 4B: Logs
            int logY = 210;
            List<ScriptReferenceDoc> logs = script.getLogFiles();
            String logTarget = !logs.isEmpty() ? shortenPath(logs.get(0).getTarget()) : "age_artabal.log";
            drawCard(g2d, col4X, logY, cardW, 90, "TIER 4B: LOG REPOSITORY", AWT_SLATE);
            g2d.setColor(new Color(0x1E, 0x29, 0x3B));
            g2d.setFont(new Font("SansSerif", Font.BOLD, 12));
            g2d.drawString(truncate(logTarget, 26), col4X + 16, logY + 48);
            g2d.setFont(new Font("SansSerif", Font.PLAIN, 11));
            g2d.setColor(new Color(0x64, 0x74, 0x8B));
            g2d.drawString("Filesystem: /fl/ars/log/", col4X + 16, logY + 70);

            // Arrow: KSH -> Log
            drawConnector(g2d, col2X + cardW, kshY + 150, col4X, logY + 45, "Redirects", AWT_SLATE);

            // Tier 4C: Mailx or Reports
            int mailY = 330;
            drawCard(g2d, col4X, mailY, cardW, 90, "TIER 4C: ALERTS & REPORTS", new Color(0xDC, 0x26, 0x26));
            g2d.setColor(new Color(0x1E, 0x29, 0x3B));
            g2d.setFont(new Font("SansSerif", Font.BOLD, 12));
