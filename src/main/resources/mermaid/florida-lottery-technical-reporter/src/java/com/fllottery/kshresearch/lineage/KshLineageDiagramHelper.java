            g2d.setColor(new Color(0x1E, 0x29, 0x3B));
            g2d.setFont(new Font("SansSerif", Font.BOLD, 13));
            g2d.drawString(truncate(procName, 26), col3X + 16, procY + 48);
            g2d.setFont(new Font("SansSerif", Font.PLAIN, 12));
