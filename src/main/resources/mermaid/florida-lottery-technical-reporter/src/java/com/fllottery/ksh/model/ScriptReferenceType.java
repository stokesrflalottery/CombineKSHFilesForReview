package com.fllottery.ksh.model;

/**
 * Enterprise classification for outgoing and incoming references mined from
 * legacy Florida Lottery Korn Shell (.ksh) and SQL (.sql) batch scripts.
 *
 * @author Ryan Stokes (Programmer Analyst III)
 * @author Florida Lottery Architecture Group
 * @version 1.1.0
 */
public enum ScriptReferenceType {

    /**
     * Oracle Stored Procedure or Package invocation via runOraclePKG.ksh, runOraclePROC.ksh,
     * PL/SQL exec statements, or custom wrappers.
     */
    ORACLE_PROCEDURE("Oracle Procedure", "Executes an Oracle Stored Procedure or Package Driver", "#5C1D48", "#FDF2F8"),

    /**
     * SQL*Plus script invocation (@path/to/script.sql, @@script.sql) or inline SQL*Plus heredoc block.
     */
    SQLPLUS_SCRIPT("SQL*Plus Script", "Executes an external .sql file or inline SQL*Plus block", "#002B49", "#EFF6FF"),

    /**
     * Sourced shell environment file (e.g. . /fl/ars/source/oltp.env or MoveAndCopyConnection).
     */
    SOURCED_ENV("Sourced Environment", "Sources environment variables, database TNS aliases, and paths", "#0D9488", "#F0FDFA"),

    /**
     * Direct invocation of another child or helper Korn Shell script (.ksh / .sh).
     */
    CHILD_KSH_SCRIPT("Child Script", "Executes a secondary child or sub-orchestrator Korn shell script", "#2563EB", "#EFF6FF"),

    /**
     * Physical database table read or modified (mined from SQL statements, spools, or comment blocks).
     */
    DATABASE_TABLE("Database Table", "Target database relational table read or modified during execution", "#7C3AED", "#F5F3FF"),

    /**
     * Execution output log file generated by stdout/stderr redirection (> or >>).
     */
    LOG_FILE("Log File", "Batch execution diagnostic log written to filesystem", "#475569", "#F8FAFC"),

    /**
     * HTML formatted operational report generated for automated distribution.
     */
    REPORT_HTML("HTML Report", "Executive or operational HTML report generated for stakeholders", "#059669", "#ECFDF5"),

    /**
     * Delimited CSV or TXT data extract generated for downstream consumption.
     */
    REPORT_CSV("CSV / Data Extract", "Delimited data export file destined for reporting or downstream systems", "#16A34A", "#F0FDF4"),

    /**
     * Spool output generated by SQL*Plus (SPOOL path or SPOOL &&1).
     */
    SQL_SPOOL_OUTPUT("SQL Spool Output", "Direct SQL*Plus spool output file destination", "#0284C7", "#F0F9FF"),

    /**
     * Input data file read or processed by the batch script or SQL*Loader.
     */
    INPUT_FILE("Input File", "Source data file, control file, or staging table dump consumed by script", "#D97706", "#FFFBEB"),

    /**
     * Output data file generated or modified.
     */
    OUTPUT_FILE("Output File", "Output file generated or moved during batch processing", "#6366F1", "#EEF2FF"),

    /**
     * Automated email notification dispatched via UNIX mailx, mail, or sendmail.
     */
    NOTIFICATION_MAILX("Notification Alert", "Automated email status alert dispatched via mailx, mail, or sendmail", "#DC2626", "#FEF2F2"),

    /**
     * Secure FTP (SFTP), FTP, or SCP file transfer to external or inter-server destinations.
     */
    SFTP_TRANSFER("SFTP / Remote Transfer", "Secure network file movement via sftp, ftp, scp, or ssh jump", "#EA580C", "#FFF7ED");

    private final String displayName;
    private final String description;
    private final String colorHex;
    private final String bgHex;

    ScriptReferenceType(String displayName, String description, String colorHex, String bgHex) {
        this.displayName = displayName;
        this.description = description;
        this.colorHex = colorHex;
        this.bgHex = bgHex;
    }

    public String getDisplayName() {
        String result = this.displayName;
        return result;
    }

    public String getDescription() {
        String result = this.description;
        return result;
    }

    public String getColorHex() {
        String result = this.colorHex;
        return result;
    }

    public String getBgHex() {
        String result = this.bgHex;
        return result;
    }

    /**
     * Helper to classify a file path into an appropriate reference type based on file extension and path semantics.
     *
     * @param path the extracted file path
     * @return the resolved ScriptReferenceType
     */
    public static ScriptReferenceType classifyFilePath(String path) {
        if (path == null || path.isBlank()) {
            ScriptReferenceType result = ScriptReferenceType.LOG_FILE;
            return result;
        }

        String lower = path.toLowerCase();
        ScriptReferenceType result;

        if (lower.endsWith(".ksh") || lower.endsWith(".sh")) {
            result = ScriptReferenceType.CHILD_KSH_SCRIPT;
        } else if (lower.endsWith(".sql")) {
            result = ScriptReferenceType.SQLPLUS_SCRIPT;
        } else if (lower.endsWith(".env")) {
            result = ScriptReferenceType.SOURCED_ENV;
        } else if (lower.endsWith(".log") || lower.contains("/log/") || lower.contains("/logs/")) {
            result = ScriptReferenceType.LOG_FILE;
        } else if (lower.endsWith(".htm") || lower.endsWith(".html")) {
            result = ScriptReferenceType.REPORT_HTML;
        } else if (lower.endsWith(".csv")) {
            result = ScriptReferenceType.REPORT_CSV;
        } else if (lower.endsWith(".txt") || lower.endsWith(".dat") || lower.endsWith(".rep") || lower.endsWith(".pdf")) {
            result = ScriptReferenceType.REPORT_CSV;
        } else {
            result = ScriptReferenceType.OUTPUT_FILE;
        }

        return result;
    }
}
